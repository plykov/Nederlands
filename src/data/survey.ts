/** Сборка текста для вставки в Telegram. */
export function buildReport(answers: Record<string, string>): string {
  const lines: string[] = [];
  lines.push("ОТЗЫВ · Nederlands Vivo · Phase 0");
  const week = answers["week"];
  if (week) lines.push(`Неделя: ${week}`);
  const nick = answers["nick"]?.trim();
  if (nick) lines.push(`Тестер: ${nick}`);
  lines.push("");

  for (const q of SURVEY) {
    if (q.id === "week" || q.id === "nick") continue;
    const a = answers[q.id]?.trim();
    if (!a) continue;
    lines.push(`▸ ${q.label}`);
    lines.push(`  ${a.replace(/\n/g, "\n  ")}`);
  }

  lines.push("");
  lines.push(`Отправлено: ${new Date().toLocaleDateString("ru-RU")}`);
  return lines.join("\n");
}
